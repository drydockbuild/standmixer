import AppKit

guard CommandLine.arguments.count == 2 else {
    fputs("Usage: swift dev/make-sidebar-icons.swift PROJECT_DIRECTORY\n", stderr)
    exit(2)
}
let root = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
let pixels = 128

func bitmap(width: Int, height: Int, draw: () -> Void) throws -> Data {
    guard let image = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height,
        bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
        colorSpaceName: .deviceRGB, bytesPerRow: width * 4, bitsPerPixel: 32),
        let context = NSGraphicsContext(bitmapImageRep: image), let bytes = image.bitmapData else {
        throw NSError(domain: "StandMixer", code: 1)
    }
    bytes.initialize(repeating: 0, count: image.bytesPerRow * height)
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = context
    context.imageInterpolation = .high
    context.shouldAntialias = true
    draw()
    NSGraphicsContext.restoreGraphicsState()
    guard let data = image.representation(using: .png, properties: [:]) else { throw NSError(domain: "StandMixer", code: 2) }
    return data
}

var entries: [String] = []
var images: [NSImage] = []
for theme in ["light", "dark"] {
    let source = theme == "dark" ? "standmixer-mark-dark.svg" : "standmixer-mark.svg"
    guard let mark = NSImage(contentsOf: root.appendingPathComponent("brand/" + source)) else { throw NSError(domain: "StandMixer", code: 3) }
    let png = try bitmap(width: pixels, height: pixels) { mark.draw(in: NSRect(x: 0, y: 0, width: pixels, height: pixels)) }
    try png.write(to: root.appendingPathComponent("brand/standmixer-sidebar-\(theme).png"))
    images.append(NSImage(data: png)!)
    entries.append("        [\"src\": \"data:image/png;base64,\(png.base64EncodedString())\", \"mimeType\": \"image/png\", \"sizes\": [\"128x128\"], \"theme\": \"\(theme)\"]")
}
let swift = """
// Generated by dev/make-sidebar-icons.swift from the brand SVGs.
enum StandMixerSidebarIcons {
    static let icons: [[String: Any]] = [
\(entries.joined(separator: ",\n"))
    ]
}

"""
try swift.write(to: root.appendingPathComponent("Sources/AgentMixHelper/SidebarIcons.swift"), atomically: true, encoding: .utf8)

let previews = root.appendingPathComponent("previews", isDirectory: true)
try FileManager.default.createDirectory(at: previews, withIntermediateDirectories: true)
let preview = try bitmap(width: 512, height: 240) {
    for i in 0...1 {
        (i == 0 ? NSColor(srgbRed: 0.96, green: 0.97, blue: 0.98, alpha: 1) : NSColor(srgbRed: 0.16, green: 0.16, blue: 0.17, alpha: 1)).setFill()
        NSBezierPath(rect: NSRect(x: i * 256, y: 0, width: 256, height: 240)).fill()
        images[i].draw(in: NSRect(x: i * 256 + 64, y: 72, width: 128, height: 128))
        let text = i == 0 ? "Light appearance" : "Dark appearance"
        let style: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 15, weight: .medium), .foregroundColor: i == 0 ? NSColor.darkGray : NSColor.lightGray]
        let size = (text as NSString).size(withAttributes: style)
        (text as NSString).draw(at: NSPoint(x: CGFloat(i * 256) + (256 - size.width) / 2, y: 31), withAttributes: style)
    }
}
try preview.write(to: previews.appendingPathComponent("sidebar-icons.png"))
